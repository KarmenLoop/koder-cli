 function checkWorksheet(text) {
  const titles=['1. 操作前的预测','2. 基准操作与结果','3. 原因解释','4. 变式与差异','5. 失败与排查','6. 交件与复做'];
  const parts=String(text).split(/^### /m),missing=[];
  for(const title of titles){
   const hits=parts.filter(s=>s.split('\n',1)[0].trim()===title);
   const section=hits.length===1?hits[0].slice(hits[0].indexOf('\n')+1).split(/^## /m)[0].trim():'';
   if(!section||/^\[在这里写：/.test(section)||/^[_\s]*$/.test(section))missing.push(title);
  }
  return {state:missing.length?'incomplete':'ready-for-human-review',missing,contentVerified:false,executionVerified:false};
 }
