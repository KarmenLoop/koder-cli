import fs from "node:fs";
import path from "node:path";
import { KoderError } from "../errors.mjs";
import { git } from "../exec.mjs";
import { yesDecision } from "../policy.mjs";
import { createSession } from "../session.mjs";
import { fixLoop, generateTests, reviewChanges } from "../workflows.mjs";
import { formatMarkdown } from "./review.mjs";

export const flags = {
  force: { type: "bool" },
  event: { type: "string" },
  out: { type: "string" },
  check: { type: "string" },
};

const TRUSTED = new Set(["OWNER", "MEMBER", "COLLABORATOR"]);
const VERBS = { review: "review", 审查: "review", fix: "fix", 修复: "fix", test: "test", 测试: "test", ask: "ask", 提问: "ask", help: "help", 帮助: "help" };

export const WORKFLOW = `# Generated by koder ci init. Review the permissions before committing.
name: Koder

on:
  pull_request:
    types: [opened, synchronize, reopened]
  issue_comment:
    types: [created]
  pull_request_review_comment:
    types: [created]

permissions:
  contents: write
  pull-requests: write
  issues: write

env:
  KODER_MODEL: \${{ secrets.KODER_MODEL }}
  KODER_BASE_URL: \${{ secrets.KODER_BASE_URL }}
  KODER_API_KEY: \${{ secrets.KODER_API_KEY }}
  KODER_LANG: __LANG__
  KODER_NO_ANIM: "1"

jobs:
  review:
    if: github.event_name == 'pull_request' && github.event.pull_request.head.repo.full_name == github.repository
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      - name: Install Koder CLI
        run: npm install -g \${{ vars.KODER_CLI_PACKAGE }}
      - name: Review
        run: koder review --base origin/\${{ github.base_ref }} --format github --out koder-review.md --fail-on high
      - name: Comment
        if: always() && hashFiles('koder-review.md') != ''
        env:
          GH_TOKEN: \${{ github.token }}
        run: gh pr comment \${{ github.event.pull_request.number }} --body-file koder-review.md

  comment:
    if: >-
      startsWith(github.event.comment.body, '/koder') &&
      contains(fromJSON('["OWNER","MEMBER","COLLABORATOR"]'), github.event.comment.author_association) &&
      (github.event_name == 'pull_request_review_comment' || github.event.issue.pull_request)
    runs-on: ubuntu-latest
    steps:
      - name: Find the pull request
        id: pr
        env:
          GH_TOKEN: \${{ github.token }}
          NUMBER: \${{ github.event.issue.number || github.event.pull_request.number }}
        run: |
          gh pr view "$NUMBER" --repo "$GITHUB_REPOSITORY" --json headRefName,baseRefName,isCrossRepository \\
            --jq '"head=\\(.headRefName)\\nbase=\\(.baseRefName)\\ncross=\\(.isCrossRepository)"' >> "$GITHUB_OUTPUT"
          echo "number=$NUMBER" >> "$GITHUB_OUTPUT"
      - uses: actions/checkout@v4
        with:
          ref: \${{ steps.pr.outputs.head }}
          fetch-depth: 0
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      - name: Install Koder CLI
        run: npm install -g \${{ vars.KODER_CLI_PACKAGE }}
      - name: Koder
        id: koder
        env:
          KODER_BASE_REF: origin/\${{ steps.pr.outputs.base }}
          KODER_CHECK: \${{ vars.KODER_CHECK }}
        run: koder ci comment --out koder-reply.md
      - name: Push fixes
        if: steps.koder.outputs.changed == 'true' && steps.pr.outputs.cross == 'false'
        run: |
          git config user.name "koder-bot"
          git config user.email "koder-bot@users.noreply.github.com"
          git add -A
          git commit -m "koder: \${{ steps.koder.outputs.command }} (#\${{ steps.pr.outputs.number }})"
          git push origin HEAD:\${{ steps.pr.outputs.head }}
      - name: Reply
        if: always() && hashFiles('koder-reply.md') != ''
        env:
          GH_TOKEN: \${{ github.token }}
        run: gh pr comment \${{ steps.pr.outputs.number }} --body-file koder-reply.md
`;

export function parseComment(body) {
  for (const raw of String(body || "").split("\n")) {
    const match = /^\s*\/koder(?:\s+(\S+))?\s*(.*)$/i.exec(raw);
    if (match) {
      const verb = VERBS[(match[1] || "review").toLowerCase()] || null;
      return verb ? { verb, rest: match[2].trim() } : { verb: "help", rest: "" };
    }
  }
  return null;
}

function helpReply(zh) {
  return zh
    ? "可用指令：\n\n- `/koder review [关注点]` 审查这个 PR\n- `/koder fix [说明]` 修复（在代码行评论里会修这一处）\n- `/koder test` 为改动补测试\n- `/koder ask <问题>` 只读提问"
    : "Commands:\n\n- `/koder review [focus]` review this PR\n- `/koder fix [notes]` fix (on a line comment, fixes that spot)\n- `/koder test` add tests for the change\n- `/koder ask <question>` read-only question";
}

async function changed(root) {
  return Boolean((await git(["status", "--porcelain"], root)).stdout.trim());
}

function setOutput(env, values) {
  if (!env.GITHUB_OUTPUT) return;
  fs.appendFileSync(env.GITHUB_OUTPUT, Object.entries(values).map(([k, v]) => `${k}=${v}\n`).join(""));
}

export async function handleComment(ctx, event, { check = "" } = {}) {
  const zh = ctx.lang === "zh";
  const comment = event?.comment;
  const parsed = parseComment(comment?.body);
  if (!parsed) return { reply: "", code: 0, ignored: true };
  const association = comment?.author_association || "NONE";
  if (!TRUSTED.has(association)) return { reply: ctx.t("ci.denied", { association }), code: 0, verb: parsed.verb, denied: true };
  const workspace = ctx.workspace();
  const location = comment.path ? `${comment.path}${comment.line ? `:${comment.line}` : ""}` : "";
  const hunk = comment.diff_hunk ? `\n\n\`\`\`diff\n${comment.diff_hunk}\n\`\`\`` : "";
  const base = ctx.env.KODER_BASE_REF || (event.pull_request?.base?.ref ? `origin/${event.pull_request.base.ref}` : undefined);
  const log = (line) => ctx.stderr.write(`${line}\n`);
  if (parsed.verb === "help") return { reply: helpReply(zh), code: 0, verb: "help" };
  if (parsed.verb === "review") {
    const result = await reviewChanges(ctx, { workspace, base, focus: parsed.rest, path: comment.path, line: comment.line, onProgress: log });
    if (result.empty) return { reply: ctx.t("err.noDiff"), code: 0, verb: "review" };
    return { reply: formatMarkdown(result, { lang: ctx.lang, t: ctx.t }), code: result.code, verb: "review" };
  }
  if (parsed.verb === "ask") {
    const session = await createSession(ctx, { workspace, interaction: "ask", quiet: true });
    const question = `${parsed.rest || (zh ? "解释这段代码" : "Explain this code")}${location ? `\n\n${zh ? "位置" : "Location"}: ${location}` : ""}${hunk}`;
    const outcome = await session.turn(question, { silent: true, decide: () => ({ cancel: true }) });
    return { reply: outcome.text || ctx.t("model.missing"), code: outcome.code, verb: "ask" };
  }
  if (parsed.verb === "fix") {
    const description = [parsed.rest || (zh ? "修复评论指出的问题" : "Fix the issue raised in the comment"), location ? `${zh ? "位置" : "Location"}: ${location}` : ""].filter(Boolean).join("\n") + hunk;
    const result = await fixLoop(ctx, { workspace, description, check, attempts: 2, decide: yesDecision, log });
    const dirty = await changed(workspace);
    const checkLine = check ? `\n\n${zh ? "检查" : "Check"} \`${check}\`: ${result.ok ? (zh ? "通过" : "passed") : zh ? "未通过" : "failed"}` : "";
    return { reply: `${dirty ? (zh ? "已提交修复。" : "Fix pushed.") : zh ? "没有产生修改。" : "No changes made."}${checkLine}`, code: result.code, verb: "fix", changed: dirty };
  }
  const result = await generateTests(ctx, { workspace, base, check, attempts: 2, decide: yesDecision, log });
  const dirty = await changed(workspace);
  return { reply: dirty ? (zh ? `已补测试：${result.files.join("、")}` : `Tests added for: ${result.files.join(", ")}`) : zh ? "没有产生修改。" : "No changes made.", code: result.code, verb: "test", changed: dirty };
}

export async function run(ctx) {
  const [action = "init"] = ctx.positionals;
  if (action === "init") {
    const file = path.join(ctx.workspace(), ".github", "workflows", "koder.yml");
    if (fs.existsSync(file) && !ctx.opts.force) throw new KoderError("ci.exists", { file }, 1);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, WORKFLOW.replace("__LANG__", ctx.lang));
    ctx.stdout.write(`${ctx.t("ci.created", { file })}\n${ctx.t("ci.secrets")}\n`);
    return 0;
  }
  if (action === "comment") {
    const eventFile = ctx.opts.event || ctx.env.GITHUB_EVENT_PATH;
    if (!eventFile || !fs.existsSync(eventFile)) throw new KoderError("ci.noEvent");
    const event = JSON.parse(fs.readFileSync(eventFile, "utf8"));
    const result = await handleComment(ctx, event, { check: ctx.opts.check || ctx.env.KODER_CHECK || "" });
    if (result.ignored) {
      ctx.stdout.write(`${ctx.t("ci.ignored")}\n`);
      return 0;
    }
    ctx.stderr.write(`${ctx.t("review.comment", { command: result.verb })}\n`);
    ctx.stdout.write(`${result.reply}\n`);
    if (ctx.opts.out) fs.writeFileSync(path.resolve(ctx.cwd, ctx.opts.out), `${result.reply}\n`);
    setOutput(ctx.env, { changed: String(Boolean(result.changed)), command: result.verb || "" });
    return result.denied ? 0 : result.code;
  }
  throw new KoderError("err.unknownCommand", { name: `ci ${action}` });
}
